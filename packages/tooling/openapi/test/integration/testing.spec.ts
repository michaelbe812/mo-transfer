/**
 * Testing preset (openapi-typescript, openapi-msw + a mocks engine: none (default: typed http only) or examples
 * (generated handlers, bodies from the spec examples)) from the fixture spec, and the generated handlers really
 * answering through msw 3 in Node (setupServer).
 */
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import type { ClientDefinition } from '../../src/adapter';
import { generateTesting, resolveClient } from '../../src/facade';
import { camelCase } from '../../src/settings';

const generateTestingLib = (client: ClientDefinition, root: string) => generateTesting(client, root, {}, {});
import {
  addClient,
  createWorkspace,
  filesBelow,
  fixture,
  hashTree,
  read,
  removeWorkspace,
  typecheck,
} from '../helpers';

const HEADER_START =
  '/* eslint-disable */\n/* eslint-enable @nx/enforce-module-boundaries, no-restricted-imports */\n// Generated by @mo-transfer/tooling (openapi, testing)';

describe('testing lib generation, mocks: none (library default: scaffold only, no generated handlers)', () => {
  let root: string;
  const clientPath = 'generated/things-client';
  const generatedDir = () => join(root, 'libs', clientPath, 'testing/src/generated');

  beforeAll(() => {
    root = createWorkspace('testing-none');
    addClient(root, clientPath);
  });
  afterAll(() => removeWorkspace(root));

  it('writes only schema, typed http and the barrel — no handlers', async () => {
    const result = await generateTestingLib(resolveClient(root, clientPath), root);
    const files = filesBelow(generatedDir());
    expect(files).toEqual(['http.ts', 'index.ts', 'schema.ts']);
    expect(result).toEqual({ baseUrl: 'http://api.test/v1', files: 3 });
    for (const file of files) {
      expect(read(generatedDir(), file).startsWith(HEADER_START)).toBe(true);
      expect(read(generatedDir(), file)).not.toMatch(/faker|MockHandler|ResponseMock|Handlers/);
    }
    expect(read(generatedDir(), 'http.ts')).toContain('export const thingsClientHttp = createOpenApiHttp<paths>');
    expect(read(generatedDir(), 'index.ts')).toContain("export * from './http';");
  });

  it('is deterministic and compiles', async () => {
    const before = hashTree(generatedDir());
    await generateTestingLib(resolveClient(root, clientPath), root);
    expect(hashTree(generatedDir())).toEqual(before);
    expect(typecheck(root, [`libs/${clientPath}/testing/src/index.ts`])).toEqual([]);
  });

  it('the typed http serves hand-written data through msw (Node)', async () => {
    const { setupServer } = await import('msw/node');
    const testing = await import(pathToFileURL(join(generatedDir(), 'index.ts')).href);
    expect(Object.keys(testing).sort()).toEqual(['thingsClientBaseUrl', 'thingsClientHttp']);
    type Resolver = (info: { response: (status: number) => { json: (body: object) => Response } }) => Response;
    const http = testing.thingsClientHttp as { get: (path: string, resolver: Resolver) => never };
    const server = setupServer(
      http.get('/owners', ({ response }) => response(200).json([{ id: 'o-7', name: 'Grace' }])),
    );
    server.listen({ onUnhandledFrame: 'error' });
    try {
      expect(await (await fetch('http://api.test/v1/owners')).json()).toEqual([{ id: 'o-7', name: 'Grace' }]);
    } finally {
      server.close();
    }
  });

  it('camelCase: client name → export prefix', () => {
    expect(camelCase('pet-client')).toBe('petClient');
    expect(camelCase('a-b2-c')).toBe('aB2C');
  });

  it('a spec without operations is fine (nothing to mock)', async () => {
    addClient(root, 'generated/empty-client', {
      spec: 'openapi: 3.0.3\ninfo: { title: Empty, version: 1.0.0 }\npaths: {}\n',
    });
    await expect(generateTestingLib(resolveClient(root, 'generated/empty-client'), root)).resolves.toMatchObject({
      files: 3,
    });
  });
});

describe('testing lib generation, mocks: examples (opt-in: generated handlers, no faker)', () => {
  let root: string;
  const clientPath = 'generated/things-client';
  const generatedDir = () => join(root, 'libs', clientPath, 'testing/src/generated');
  const generateExamples = () => generateTestingLib(resolveClient(root, clientPath), root);

  beforeAll(() => {
    root = createWorkspace('testing-examples');
    addClient(root, clientPath, { entry: { pipeline: { testing: { mocks: 'examples' } } } });
  });
  afterAll(() => removeWorkspace(root));

  it('writes schema, http, handlers, index — no mocks, no runtime, no faker', async () => {
    const result = await generateExamples();
    const files = filesBelow(generatedDir());
    expect(files.sort()).toEqual(['handlers.ts', 'http.ts', 'index.ts', 'schema.ts']);
    expect(result).toEqual({ baseUrl: 'http://api.test/v1', files: 4 });
    for (const file of files) {
      expect(read(generatedDir(), file).startsWith(HEADER_START)).toBe(true);
      expect(read(generatedDir(), file)).not.toMatch(/faker|ResponseMock|MockHandler/);
    }
    expect(read(generatedDir(), 'handlers.ts')).toContain('export const thingsClientHandlers: HttpHandler[] = [');
    expect(read(generatedDir(), 'handlers.ts')).toContain(
      'thingsClientHttp.get("/things/{id}", ({ response }) => response(200).json({"id":"t-1","name":"Lamp","kind":"tool"})),',
    );
  });

  it('is deterministic and compiles — the typecheck checks the generated bodies against the spec', async () => {
    const before = hashTree(generatedDir());
    await generateExamples();
    expect(hashTree(generatedDir())).toEqual(before);
    expect(typecheck(root, [`libs/${clientPath}/testing/src/index.ts`], ['lib.es2020.d.ts', 'lib.dom.d.ts'])).toEqual([]);
  });

  it('the handlers answer through msw (Node): spec examples, placeholders for the rest — same data per request', async () => {
    const { setupServer } = await import('msw/node');
    const testing = await import(pathToFileURL(join(generatedDir(), 'index.ts')).href);
    expect(Object.keys(testing).sort()).toEqual(['thingsClientBaseUrl', 'thingsClientHandlers', 'thingsClientHttp']);
    const server = setupServer(...testing.thingsClientHandlers);
    server.listen({ onUnhandledFrame: 'error' });
    try {
      const things = await (await fetch('http://api.test/v1/things')).json();
      expect(things).toEqual([{ id: 't-1', name: 'Lamp', kind: 'tool', owner: { id: 'o-1', name: 'Ada' } }]);
      const thing = await (await fetch('http://api.test/v1/things/t-9')).json();
      expect(thing).toEqual({ id: 't-1', name: 'Lamp', kind: 'tool' });
      expect(await (await fetch('http://api.test/v1/things/t-9')).json()).toEqual(thing);
      expect(await (await fetch('http://api.test/v1/owners')).json()).toEqual([{ id: 'o-1', name: 'Ada' }]);
    } finally {
      server.close();
    }
  });

  it('a spec without operations: empty handler list', async () => {
    addClient(root, 'generated/empty-client', {
      spec: 'openapi: 3.0.3\ninfo: { title: Empty, version: 1.0.0 }\npaths: {}\n',
      entry: { pipeline: { testing: { mocks: 'examples' } } },
    });
    await generateTestingLib(resolveClient(root, 'generated/empty-client'), root);
    expect(read(root, 'libs/generated/empty-client/testing/src/generated/handlers.ts')).toContain('export const emptyClientHandlers: HttpHandler[] = [\n];');
  });

  it('an unknown mocks engine fails with a hint', async () => {
    addClient(root, 'generated/odd-client', { entry: { pipeline: { testing: { mocks: 'nope' } } } });
    await expect(generateTestingLib(resolveClient(root, 'generated/odd-client'), root)).rejects.toMatchObject({
      message: 'unknown mocks engine "nope" (none | examples)',
    });
  });
});

describe('testing lib generation: errors', () => {
  let root: string;
  beforeAll(() => {
    root = createWorkspace('testing-errors');
  });
  afterAll(() => removeWorkspace(root));

  it('fails without spec file', async () => {
    const client: ClientDefinition = {
      name: 'x-client',
      path: 'generated/x-client',
      placement: 'shared',
      spec: { file: 'libs/generated/x-client/openapi.yaml' },
      generator: { adapter: 'openapi-tools', options: {} },
      layout: 'default',
      pipeline: {},
    };
    await expect(generateTestingLib(client, root)).rejects.toThrow('libs/generated/x-client/openapi.yaml missing');
  });

  it('fails without the committed testing index.ts', async () => {
    addClient(root, 'generated/no-testing-client', { parts: ['types', 'api', 'core'] });
    await expect(generateTestingLib(resolveClient(root, 'generated/no-testing-client'), root)).rejects.toThrow(
      "testing/src/index.ts missing (export * from './generated';)",
    );
  });

  it('a spec without servers gets baseUrl ""', async () => {
    addClient(root, 'booking/generated/ping-client', { spec: fixture('no-models.yaml').replace(/servers:\n.*\n/, '') });
    const result = await generateTestingLib(resolveClient(root, 'booking/generated/ping-client'), root);
    expect(result.baseUrl).toBe('');
    expect(read(root, 'libs/booking/generated/ping-client/testing/src/generated/http.ts')).toContain(
      'export const pingClientBaseUrl = "";',
    );
  });
});
